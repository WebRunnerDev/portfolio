// ADR-0007: physical direction classes are banned. The rule also maps
// width/height and the vertical axis to block/inline classes — that only
// matters for vertical writing modes, which we don't use, so those are ignored.
const logicalPropertiesIgnore = [
  "(^|:)(min-|max-)?[wh]-",
  "(^|:)size-",
  "(^|:)-?(top|bottom)-",
  "(^|:)-?(scroll-)?[mp][tb]-",
  "(^|:)border-[tb](-|$)",
]

// ADR-0008: `start-*`/`end-*` are deprecated since Tailwind 4.2.
const deprecatedInsetRestrictions = [
  {
    pattern: "^(.*:)?(-?)start-(.+)$",
    fix: "$1$2inset-s-$3",
    message: "`start-*` is deprecated in Tailwind 4.2, use `inset-s-*`.",
  },
  {
    pattern: "^(.*:)?(-?)end-(.+)$",
    fix: "$1$2inset-e-$3",
    message: "`end-*` is deprecated in Tailwind 4.2, use `inset-e-*`.",
  },
]

